"""Rebuild PDF resources: python scripts/prepare-checkup-pdf.py FONT_DIR

FONT_DIR contains Questrial.ttf, Inter.ttf and Montserrat.ttf from google/fonts.
Requires fontTools, PyMuPDF and Inkscape. Normal site builds use the committed
resources and do not download fonts or run this script.
"""
import base64
import io
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

import fitz
from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

root = Path(__file__).resolve().parents[1]
input_dir = Path(sys.argv[1])
pdf = fitz.open()
page = pdf.new_page(width=595, height=842)
glyphs = {}
for family, axes in (("Inter", {"opsz": 14, "wght": 400}),
                     ("Montserrat", {"wght": 600}), ("Questrial", {})):
    font = TTFont(input_dir / (family + ".ttf"))
    if axes:
        font = instantiateVariableFont(font, axes, updateFontNames=True)
    latin = subset.Subsetter()
    latin.populate(unicodes=[*range(32, 127), *range(160, 256), *range(0x2010, 0x2027), 0x20ac])
    latin.subset(font)
    buf = io.BytesIO()
    font.save(buf)
    page.insert_font(fontname=family, fontbuffer=buf.getvalue())
    units = font["head"].unitsPerEm
    glyphs[family] = {
        chr(code): [format(font.getGlyphID(name), "04x"), round(1000 * font["hmtx"][name][0] / units)]
        for code, name in font.getBestCmap().items()
    }

with tempfile.TemporaryDirectory() as tmp:
    logo_path = Path(tmp) / "logo.pdf"
    subprocess.run(["inkscape", str(root / "public/assets/road-logo-cafe.svg"),
                    "--export-filename=" + str(logo_path)], check=True)
    with fitz.open(logo_path) as logo:
        page.show_pdf_page(fitz.Rect(508, 31, 550, 97), logo, 0, keep_proportion=True)
page.insert_link({"kind": fitz.LINK_URI, "from": fitz.Rect(44, 782, 183, 813),
                  "uri": "https://wa.me/5542984242852?text=Ol%C3%A1%21%20Realizei%20o%20Check-up%20ROAD%20e%20gostaria%20de%20conversar%20sobre%20minha%20an%C3%A1lise%20patrimonial."})
# The Worker writes the variable page text into this object as a PDF incremental update.
target = pdf.get_new_xref()
pdf.update_object(target, "<<>>")
pdf.update_stream(target, b"q Q")
previous = " ".join(f"{x} 0 R" for x in page.get_contents())
pdf.xref_set_key(page.xref, "Contents", f"[{previous} {target} 0 R]")
base = pdf.tobytes(deflate=True, garbage=0, no_new_id=True)
metadata = {"object": target, "root": pdf.pdf_catalog(), "size": pdf.xref_length(),
            "xref": int(re.search(rb"startxref\s+(\d+)\s+%%EOF\s*$", base).group(1))}
out = root / "src/pdf-assets/checkup-base.js"
with out.open("w") as f:
    f.write("// Generated by scripts/prepare-checkup-pdf.py. Fonts licensed under adjacent OFLs.\n")
    for key, value in (("base64", base64.b64encode(base).decode()), ("metadata", metadata), ("glyphs", glyphs)):
        f.write(f"export const {key} = " + json.dumps(value, ensure_ascii=True, separators=(",", ":")) + ";\n")
